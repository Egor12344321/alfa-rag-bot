def build_intent_user(text: str, now_iso: str, history: list[str]) -> str:
    hist = "\n".join(history[-6:])
    return (
        f"Текущая дата и время с часовым поясом: {now_iso}\n\n"
        f"История:\n{hist}\n\n"
        f"Сообщение:\n{text}"
    )


